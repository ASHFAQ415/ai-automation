# 2. Payment Provider
# ?????????????????????????????????????????????????????????????????????????????

class BasePaymentProvider(ABC):
    @abstractmethod
    def create_payment_link(self, lead_id: int, amount: int, currency: str = "INR") -> str:
        pass

    @abstractmethod
    def verify_webhook(self, body: bytes, signature: str) -> bool:
        pass


class MockPaymentProvider(BasePaymentProvider):
    """Deterministic mock payment gateway."""

    def create_payment_link(self, lead_id: int, amount: int, currency: str = "INR") -> str:
        return f"http://localhost:8000/api/payments/simulate/{lead_id}?amount={amount}&currency={currency}"

    def verify_webhook(self, body: bytes, signature: str) -> bool:
        return signature == "mock_valid_signature" or signature is not None


