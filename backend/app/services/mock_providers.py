# 3. WhatsApp Provider
# ?????????????????????????????????????????????????????????????????????????????

class BaseWhatsAppProvider(ABC):
    @abstractmethod
    async def send_message(self, to_phone: str, text: str) -> bool:
        pass


class MockWhatsAppProvider(BaseWhatsAppProvider):
    """Deterministic mock WhatsApp messenger capturing sent messages in memory."""
    sent_messages: list[dict[str, str]] = []

    async def send_message(self, to_phone: str, text: str) -> bool:
        self.sent_messages.append({"to": to_phone, "text": text})
        return True


