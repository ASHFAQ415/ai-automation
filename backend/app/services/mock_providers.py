"""Deterministic Mock Provider Implementations for CI and Local Testing (Section 14A.2).
Ensures CI and automated test suites never require live external services
(Ollama, Groq, Razorpay, Stripe, WhatsApp, Telegram, Discord, Cloudflare, SMTP).
Activated when TEST_MODE=true or running pytest.
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any

