# 1. LLM Provider
# ?????????????????????????????????????????????????????????????????????????????

class BaseLLMProvider(ABC):
    @abstractmethod
    async def generate_text(self, prompt: str, system_prompt: str | None = None, max_tokens: int = 1500) -> str:
        pass

    @abstractmethod
    async def score_lead(self, lead_data: dict[str, Any]) -> dict[str, Any]:
        pass

    @abstractmethod
    async def generate_plan(self, lead_data: dict[str, Any], analysis: dict[str, Any]) -> dict[str, Any]:
        pass


class MockLLMProvider(BaseLLMProvider):
    """Deterministic mock LLM provider for tests and CI."""

    async def generate_text(self, prompt: str, system_prompt: str | None = None, max_tokens: int = 1500) -> str:
        return "print('Mock Generated Application Code')"

    async def generate_structured(self, prompt: str, system_prompt: str | None = None) -> dict[str, Any]:
        prompt_lower = prompt.lower()
        if "score" in prompt_lower or "qualify" in prompt_lower:
            return {"score": 85, "temperature": "HOT", "reason": "High business intent"}
        if "plan" in prompt_lower or "feature" in prompt_lower:
            return {"title": "Autonomous Deliverable", "core_features": ["Dashboard", "API"]}
        return {"status": "success", "result": "Deterministic Mock Output", "prompt_echo": prompt[:40]}

    async def score_lead(self, lead_data: dict[str, Any]) -> dict[str, Any]:
        req = (lead_data.get("requirement") or "").lower()
        score = 85 if any(k in req for k in ["urgent", "build", "crm", "system", "pos", "portal"]) else 60
        temp = "HOT" if score >= 75 else "WARM"
        return {
            "score": score,
            "temperature": temp,
            "reason": "Deterministic Mock Qualification",
            "detected_needs": ["Deterministic Mock Automation"],
            "recommended_deliverable": "Mock Full-Stack Deliverable",
            "estimated_value": lead_data.get("budget") or "?35,000 - ?50,000"
        }

    async def generate_plan(self, lead_data: dict[str, Any], analysis: dict[str, Any]) -> dict[str, Any]:
        comp = lead_data.get("company") or lead_data.get("name") or "Client"
        return {
            "title": f"{comp} Enterprise Automation System",
            "target_deliverable": "Autonomous Web Application Suite",
            "core_features": ["Core REST APIs", "Data Management Table", "Live Metrics Cards", "CSV Exporter"],
            "tech_stack": ["FastAPI", "Pydantic v2", "Vanilla JS", "Glassmorphism CSS"],
            "architecture_overview": "Deterministic mock architecture blueprint for CI verification.",
            "implementation_steps": [
                {"step": 1, "title": "Config", "description": "Dependencies", "files": ["requirements.txt"]},
                {"step": 2, "title": "Backend", "description": "FastAPI routes", "files": ["main.py"]},
                {"step": 3, "title": "Frontend", "description": "Interactive UI", "files": ["index.html"]},
                {"step": 4, "title": "Runner", "description": "Batch script", "files": ["run_local.bat"]}
            ]
        }


